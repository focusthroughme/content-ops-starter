// Packs the web app (../index.html) and the starter data (../seed.json) into web.js for the native shell.
// Run with: npm run bundle-web   (do this again whenever index.html changes)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const page = readFileSync(join(root, '..', 'index.html'), 'utf8');
const seed = JSON.parse(readFileSync(join(root, '..', 'seed.json'), 'utf8'));
const html = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">' +
  '<style>:root{padding:env(safe-area-inset-top,0px) 0 env(safe-area-inset-bottom,0px)}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style></head><body>' + page + '</body></html>';
writeFileSync(join(root, 'web.js'), `// Generated by scripts/bundle-web.mjs. Do not edit.\nexport const HTML = ${JSON.stringify(html)};\nexport const SEED = ${JSON.stringify(seed)};\n`);
console.log(`web.js written: ${(html.length / 1024).toFixed(0)} KB page, ${seed.videos.length} archive records`);
